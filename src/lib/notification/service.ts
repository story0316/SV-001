// 보호자에게 무응답 알림
export async function notifyGuardianUnresponsive(
  guardianId: string,
  clientId: string,
  clientName: string,
  workerName: string,
  workerPhone: string
) {
  const message =
    `안녕하세요.\n` +
    `어머니/아버지 ${clientName}님의 응답이 오늘 아직 없어요.\n` +
    `담당 복지사 ${workerName}님도 함께 확인하고 있습니다.\n` +
    `걱정되시면 ${workerPhone}으로 연락 주세요.`;

  return sendNotification({
    recipientId: guardianId,
    clientId,
    type: "unresponsive",
    message,
    channel: "push",
    isAutoGenerated: true,
  });
}

// 복지사에게 위험도 상승 알림
export async function notifyWorkerRiskAlert(
  workerId: string,
  clientId: string,
  clientName: string,
  riskScore: number,
  riskFactors: string[]
) {
  const factorText = riskFactors.slice(0, 2).join(", ");
  const message =
    `🔴 ${clientName}님 위험도 상승 (${riskScore}점)\n` +
    `주요 원인: ${factorText}\n` +
    `오늘 중 확인이 필요합니다.`;

  return sendNotification({
    recipientId: workerId,
    clientId,
    type: "risk_alert",
    message,
    channel: "push",
    isAutoGenerated: true,
  });
}

// 보호자 알림 초안 자동 생성 (복지사 검토용)
export function generateGuardianNotifyDraft(
  clientName: string,
  workerName: string,
  workerPhone: string,
  reason: "unresponsive" | "warning"
): string {
  if (reason === "unresponsive") {
    return (
      `안녕하세요.\n\n` +
      `${clientName}님의 담당 복지사 ${workerName}입니다.\n\n` +
      `오늘 안부 연락을 드렸으나 연결이 어려웠습니다.\n` +
      `직접 연락해보시거나 걱정되시면 저에게 연락 주세요.\n\n` +
      `담당 복지사 ${workerName}\n${workerPhone}`
    );
  }
  return (
    `안녕하세요.\n\n` +
    `${clientName}님의 최근 상태에 변화가 감지되어\n` +
    `연락드립니다. 담당 복지사가 확인 중입니다.\n\n` +
    `담당 복지사 ${workerName}\n${workerPhone}`
  );
}
