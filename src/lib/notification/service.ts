/**
 * 알림 서비스 (notification_flow.md 기반)
 *
 * 채널 우선순위:
 *   1. Push (FCM) — 즉시
 *   2. KakaoTalk — 즉시
 *   3. Email (SendGrid) — 백업
 *   4. SMS — 긴급만
 */

import { createServerClient } from "@/lib/supabase/server";

export type NotificationType =
  | "unresponsive"   // 무응답 알림 (보호자)
  | "risk_alert"     // 위험도 상승 (복지사)
  | "action_needed"; // 조치 필요 (복지사)

interface SendNotificationOptions {
  recipientId: string;
  clientId: string;
  type: NotificationType;
  message: string;
  channel: "push" | "email" | "sms" | "kakao";
  isAutoGenerated?: boolean;
}

// 알림 발송 + DB 기록
export async function sendNotification(opts: SendNotificationOptions) {
  const supabase = createServerClient();

  // 1. 중복 발송 방지: 최근 24h 이내 같은 타입 알림이 있으면 skip
  const yesterday = new Date(Date.now() - 24 * 60 * 60 * 1000).toISOString();
  const { data: existing } = await supabase
    .from("notifications")
    .select("id")
    .eq("recipient_id", opts.recipientId)
    .eq("client_id", opts.clientId)
    .eq("type", opts.type)
    .gte("sent_at", yesterday)
    .limit(1);

  if (existing && existing.length > 0) {
    console.log(`[Notification] Skipped duplicate: ${opts.type} for ${opts.clientId}`);
    return { skipped: true };
  }

  // 2. 실제 채널 발송 (외부 API)
  await dispatchChannel(opts);

  // 3. 알림 기록 DB 저장
  const { data, error } = await supabase.from("notifications").insert({
    recipient_id: opts.recipientId,
    client_id: opts.clientId,
    type: opts.type,
    channel: opts.channel,
    message: opts.message,
    is_auto_generated: opts.isAutoGenerated ?? true,
  }).select().single();

  if (error) {
    console.error("[Notification] DB insert error:", error);
  }

  return { sent: true, id: data?.id };
}

async function dispatchChannel(opts: SendNotificationOptions) {
  switch (opts.channel) {
    case "push":
      await sendPushNotification(opts.recipientId, opts.message);
      break;
    case "kakao":
      // KakaoTalk 채널 메시지 (Phase 2에서는 stub)
      console.log(`[Kakao Notify] → ${opts.recipientId}: ${opts.message}`);
      break;
    case "email":
      // SendGrid (Phase 2에서는 stub)
      console.log(`[Email Notify] → ${opts.recipientId}: ${opts.message}`);
      break;
    case "sms":
      console.log(`[SMS Notify] → ${opts.recipientId}: ${opts.message}`);
      break;
  }
}

